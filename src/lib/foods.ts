export const FOOD_DB: FoodDef[] = ROWS.map(([n, unit, base, step, k, p, c, f, g, x]) => ({ n, unit, base, step, k, p, c, f, g, ...x }));

const num = (x: number) => (Number.isInteger(x) ? String(x) : x.toFixed(1).replace(/\.0$/, ''));

/** "175g", "1.5공기 (315g)", "2개" */
export function amountLabel(d: Pick<FoodDef, 'unit' | 'gPer'>, amt: number): string {
  if (d.unit === 'g' || d.unit === 'ml') return `${num(amt)}${d.unit}`;
  return `${num(amt)}${d.unit}${d.gPer ? ` (${Math.round(d.gPer * amt)}g)` : ''}`;
}

/** "닭가슴살 175g" */
export function foodLabel(d: FoodDef, amt = d.base): string {
  return `${d.n} ${amountLabel(d, amt)}`;
}

export interface Macros { k: number; p: number; c: number; f: number }

export function macrosOf(d: Macros & { base: number }, amt: number): Macros {
  const r = amt / d.base;
  return { k: d.k * r, p: d.p * r, c: d.c * r, f: d.f * r };
}

/** As a plain serving, for the "pick a food" list. */
export const FOODS: Food[] = FOOD_DB.map((d) => ({ n: foodLabel(d), k: d.k, p: d.p, c: d.c, f: d.f }));

/** The built-in food a logged meal came from (older names like "두부 반 모 (150g)" match by prefix). */
export function findFood(name: string): FoodDef | undefined {
  let best: FoodDef | undefined;
  for (const d of FOOD_DB) {
    if ((name === d.n || name.startsWith(`${d.n} `)) && (!best || d.n.length > best.n.length)) best = d;
  }
  return best;
}
